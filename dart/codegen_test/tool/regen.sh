#!/bin/bash
# Regenerates the generated code of this package from fixtures/schemas and checks it.
#
#   tool/regen.sh            regenerate lib/*.dart and test/messages.g.dart, check formatting
#   tool/regen.sh --check    only check that the committed files are up to date and formatted
#   tool/regen.sh --vectors  additionally regenerate fixtures/rust_vectors.json (and
#                            test/rust_vectors.g.dart) with the Rust runtime (tool/rust_vectors)
#
# Environment: DART (dart executable), CARGO_TARGET_DIR (default: <repo>/target).
set -euo pipefail
cd "$(dirname "$0")/.."
PKG=$(pwd)
ROOT=$(cd ../.. && pwd)
DART=${DART:-dart}
MODE=${1:-}
export CARGO_TARGET_DIR=${CARGO_TARGET_DIR:-$ROOT/target}

(cd "$ROOT" && cargo build -q --bin bitis)
BITIS="$CARGO_TARGET_DIR/debug/bitis"

S=fixtures/schemas
CARA=(-i $S/cara/messages_std.bitis -i $S/cara/messages_dts.bitis -i $S/cara/messages_hs.bitis
      -i $S/cara/msg_dev_server_comm.bitis -i $S/cara/messages_sts.bitis)
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# name, compiler arguments
generate() {
  local out=$1; shift
  "$BITIS" compile -l "$LANG_" -o "$out" "$@"
}
LANG_=dart
mkdir -p "$TMP/lib"
generate "$TMP/lib/test_schema.dart" -i $S/test.bitis
generate "$TMP/lib/cara.dart" "${CARA[@]}"
generate "$TMP/lib/all_types.dart" -i $S/all_types.bitis
generate "$TMP/lib/stress.dart" -i $S/stress.bitis

# registry of all messages for the tests
{
  echo "// GENERATED by tool/regen.sh. Do not edit."
  echo "// ignore_for_file: lines_longer_than_80_chars"
  echo
  echo "import 'package:bitis_codegen_test/all_types.dart' as all_types;"
  echo "import 'package:bitis_codegen_test/cara.dart' as cara;"
  echo "import 'package:bitis_codegen_test/stress.dart' as stress;"
  echo "import 'package:bitis_codegen_test/test_schema.dart' as test_schema;"
  echo
  echo "import 'message_ops.dart';"
  echo
  echo "/// All generated messages: schema -> message name -> operations."
  echo "final messages = <String, Map<String, MessageOps>>{"
  for lib in all_types cara stress test_schema; do
    echo "  '$lib': {"
    # every message class has exactly one constructor documented like this
    sed -nE 's#^  /// Creates a \[([A-Za-z0-9_]+)\]; omitted attributes get their default values\.$#\1#p' "$TMP/lib/$lib.dart" \
      | while read -r m; do
      echo "    '$m': MessageOps($lib.$m.new, $lib.$m.fromJson, $lib.$m.fromBytes, $lib.$m.fromBytesExact, $lib.$m.bitisMinBits, (m) => (m as $lib.$m).toJson()),"
    done
    echo "  },"
  done
  echo "};"
} > "$TMP/messages.g.dart"
"$DART" format --language-version=3.7 "$TMP/messages.g.dart" > /dev/null

# formatting: without the `dart format off` marker, dart format (tall style) must not change the code
mkdir -p "$TMP/fmt"
for f in "$TMP"/lib/*.dart; do sed '/^\/\/ dart format off$/d' "$f" > "$TMP/fmt/$(basename "$f")"; done
if ! "$DART" format --language-version=3.7 --output=none --set-exit-if-changed "$TMP/fmt" > "$TMP/fmt.log"; then
  cat "$TMP/fmt.log"
  echo "error: generated code is not formatted like dart format" >&2
  exit 1
fi

if [ "$MODE" == "--check" ]; then
  status=0
  for f in "$TMP"/lib/*.dart; do
    cmp -s "$f" "lib/$(basename "$f")" || { echo "lib/$(basename "$f") is out of date" >&2; status=1; }
  done
  cmp -s "$TMP/messages.g.dart" test/messages.g.dart || { echo "test/messages.g.dart is out of date" >&2; status=1; }
  exit $status
fi
cp "$TMP"/lib/*.dart lib/
cp "$TMP/messages.g.dart" test/messages.g.dart
echo "regenerated lib/*.dart and test/messages.g.dart"

if [ "$MODE" == "--vectors" ]; then
  LANG_=rust
  V=tool/rust_vectors
  mkdir -p $V/src/gen
  generate $V/src/gen/test_schema.rs -i $S/test.bitis
  generate $V/src/gen/cara.rs "${CARA[@]}"
  generate $V/src/gen/all_types.rs -i $S/all_types.bitis
  cargo run -q --manifest-path $V/Cargo.toml -- "$PKG/fixtures/vector_inputs.json" > "$TMP/rust_vectors.json"
  cp "$TMP/rust_vectors.json" fixtures/rust_vectors.json
  {
    echo "// GENERATED by tool/regen.sh from fixtures/rust_vectors.json. Do not edit."
    echo "// ignore_for_file: lines_longer_than_80_chars"
    echo
    echo "/// fixtures/rust_vectors.json (byte vectors produced by the Rust runtime)."
    echo "const rustVectorsJson = r'''"
    cat fixtures/rust_vectors.json
    echo "''';"
  } > test/rust_vectors.g.dart
  echo "regenerated fixtures/rust_vectors.json and test/rust_vectors.g.dart"
fi
