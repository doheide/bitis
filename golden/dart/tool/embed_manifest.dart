// Embeds golden/vectors/manifest.txt into test/manifest.g.dart, so that the
// tests also run in the browser (dart2js, dart2wasm), where there is no file
// I/O.
//
//   dart run tool/embed_manifest.dart          rewrite test/manifest.g.dart
//   dart run tool/embed_manifest.dart --check  exit 1 if it is out of date
//
// Paths are relative to the package directory (golden/dart); the script can
// be started from any directory.
import 'dart:io';

/// The content of test/manifest.g.dart for the manifest text [manifest].
String render(String manifest) {
  if (manifest.contains("'''")) {
    throw const FormatException("the manifest must not contain '''");
  }
  return '// GENERATED by tool/embed_manifest.dart from '
      'golden/vectors/manifest.txt. Do not edit.\n'
      '// ignore_for_file: lines_longer_than_80_chars\n'
      '\n'
      '/// Content of golden/vectors/manifest.txt, embedded because the web\n'
      '/// platforms have no file I/O (regenerate with\n'
      '/// `dart run tool/embed_manifest.dart`).\n'
      "const goldenManifest = r'''\n"
      '$manifest'
      "''';\n";
}

void main(List<String> args) {
  final check = args.contains('--check');
  if (args.any((a) => a != '--check')) {
    stderr.writeln('usage: dart run tool/embed_manifest.dart [--check]');
    exit(2);
  }
  final pkg = File.fromUri(Platform.script).parent.parent;
  final manifest = File('${pkg.path}/../vectors/manifest.txt');
  final out = File('${pkg.path}/test/manifest.g.dart');
  final content = render(manifest.readAsStringSync());
  if (check) {
    if (!out.existsSync() || out.readAsStringSync() != content) {
      stderr.writeln(
        'golden/dart/test/manifest.g.dart is out of date, run '
        'dart run tool/embed_manifest.dart',
      );
      exit(1);
    }
    return;
  }
  out.writeAsStringSync(content);
  stdout.writeln('wrote ${out.path}');
}
