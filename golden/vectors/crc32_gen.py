#!/usr/bin/env python3
"""Writes golden/vectors/crc32.txt (CRC-32/ISO-HDLC test vectors, see golden/README.md).

The expected values come from Python's zlib.crc32, an implementation independent of
the bitis runtimes.

    python3 golden/vectors/crc32_gen.py          rewrite crc32.txt
    python3 golden/vectors/crc32_gen.py --check  exit 1 if crc32.txt is out of date
"""
import pathlib
import sys
import zlib


def lcg_bytes(n, seed=0x12345678):
    """n pseudo-random bytes: x = (x * 1664525 + 1013904223) mod 2^32, byte = x >> 24
    (x updated before each byte, starting from seed)."""
    x = seed
    out = bytearray()
    for _ in range(n):
        x = (x * 1664525 + 1013904223) & 0xFFFFFFFF
        out.append(x >> 24)
    return bytes(out)


ASCII = [
    ("check", "123456789"),
    ("ascii_a", "a"),
    ("ascii_abc", "abc"),
    ("ascii_alphabet", "abcdefghijklmnopqrstuvwxyz"),
]
HEX = [
    ("empty", b""),
    ("byte_00", b"\x00"),
    ("byte_ff", b"\xff"),
    ("byte_01", b"\x01"),
    ("byte_80", b"\x80"),
    ("zeros_4", b"\x00" * 4),
    ("ones_4", b"\xff" * 4),
    ("zeros_32", b"\x00" * 32),
    ("ones_32", b"\xff" * 32),
    ("quick_brown_fox", b"The quick brown fox jumps over the lazy dog"),
    ("counting_256", bytes(range(256))),
    ("lcg_1000", lcg_bytes(1000)),
]


def render():
    lines = [
        "# CRC-32/ISO-HDLC test vectors -- GENERATED by golden/vectors/crc32_gen.py (zlib.crc32),",
        "# do not edit (see golden/README.md, section CRC-32)",
        "# reflected poly 0xedb88320, init 0xffffffff, xorout 0xffffffff (= zlib.crc32)",
        "# hex   <name> <input_hex> <crc32>   input lower-case hex, '-' = empty input",
        "# ascii <name> <input>     <crc32>   input = the ASCII bytes of the text (no spaces)",
        "# <crc32>: 8 lower-case hex digits",
        "# lcg_1000: x = 0x12345678; 1000 times: x = (x * 1664525 + 1013904223) mod 2^32,",
        "#           emit byte x >> 24",
    ]
    for name, text in ASCII:
        assert " " not in text and text.isascii() and text.isprintable()
        lines.append(f"ascii {name} {text} {zlib.crc32(text.encode()):08x}")
    for name, data in HEX:
        lines.append(f"hex {name} {data.hex() or '-'} {zlib.crc32(data):08x}")
    return "\n".join(lines) + "\n"


def main():
    out = pathlib.Path(__file__).with_name("crc32.txt")
    content = render()
    if sys.argv[1:] == ["--check"]:
        if not out.exists() or out.read_text() != content:
            print("golden/vectors/crc32.txt is out of date, run golden/vectors/crc32_gen.py")
            sys.exit(1)
        return
    if sys.argv[1:]:
        print(__doc__)
        sys.exit(2)
    out.write_text(content)
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
